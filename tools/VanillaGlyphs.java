import javax.imageio.ImageIO;
import java.nio.file.*;
import java.util.*;
import java.util.zip.ZipFile;

/**
 * Measures vanilla textures listed in tools/dex_vanilla.txt and writes src/main/resources/bundled-vanilla-glyphs.yml.
 * Only sizes are stored: the pack's fonts point at the client's own textures, so nothing from Minecraft is shipped.
 *
 * java tools/VanillaGlyphs.java "%APPDATA%/.minecraft/versions/26.3/26.3.jar" tools/dex_vanilla.txt src/main/resources/bundled-vanilla-glyphs.yml
 */
public class VanillaGlyphs {
    public static void main(String[] args) throws Exception {
        StringBuilder out = new StringBuilder("# Generated by tools/VanillaGlyphs.java from the 26.3 client. Glyphs that reference vanilla textures.\n"
                + "# ascent min(8, height): each glyph hangs from the text line its top sits on (see ResourcePackGenerator).\nvanilla:\n");
        try (ZipFile client = new ZipFile(args[0])) {
            for (String line : Files.readAllLines(Path.of(args[1]))) {
                line = line.strip();
                if (line.isEmpty() || line.startsWith("#")) continue;
                String[] p = line.split("\\s+");
                String id = p[0], texture = p[1];
                int height = Integer.parseInt(p[2]);
                String[] key = texture.split(":", 2);
                String path = "assets/" + key[0] + "/textures/" + key[1];
                if (client.getEntry(path + ".mcmeta") != null) throw new IllegalArgumentException("Animated textures are not supported: " + texture);
                var entry = client.getEntry(path);
                if (entry == null) throw new IllegalArgumentException("Missing texture: " + texture);
                var image = ImageIO.read(client.getInputStream(entry));
                int right = 0;
                for (int x = image.getWidth() - 1; x >= 0 && right == 0; x--)
                    for (int y = 0; y < image.getHeight(); y++)
                        if ((image.getRGB(x, y) >>> 24) != 0) { right = x + 1; break; }
                float scale = (float) height / image.getHeight();
                int width = Math.round(image.getWidth() * scale);
                int advance = (int) (right * scale + 0.5F) + 1;
                out.append("  ").append(id).append(":\n")
                        .append("    texture: ").append(texture).append('\n')
                        .append("    width: ").append(width).append('\n')
                        .append("    height: ").append(height).append('\n')
                        .append("    ascent: ").append(Math.min(8, height)).append('\n')
                        .append("    advance: ").append(advance).append('\n');
            }
        }
        Files.writeString(Path.of(args[2]), out);
        System.out.println("wrote " + out.toString().lines().filter(l -> l.matches("  \\S+:")).count() + " vanilla glyphs");
    }
}
