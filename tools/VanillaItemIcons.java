import javax.imageio.ImageIO;
import java.nio.file.*;
import java.util.*;
import java.util.regex.*;
import java.util.zip.ZipFile;

/**
 * Builds src/main/resources/bundled-vanilla-items.yml: one 16 px icon glyph "item/<item id>" for every vanilla item,
 * pointing at the client's own flat texture (item sprite, or a representative face of the block). Only sizes are
 * stored; nothing from Minecraft is shipped. Animated textures and items without a usable texture are skipped.
 *
 * Every icon only gets the font provider for text-line offset 2 ("offsets: [2]"), which keeps ~1,600 icons cheap:
 * draw them only at a y where y % 9 == 2 (e.g. 2 px below a slot whose top is on a 9 px line).
 *
 * java tools/VanillaItemIcons.java "%APPDATA%/.minecraft/versions/26.3/26.3.jar" src/main/resources/bundled-vanilla-items.yml
 */
public class VanillaItemIcons {
    static final Pattern MODEL = Pattern.compile("\"(?:model|base)\"\\s*:\\s*\"([a-z0-9_:/.-]+)\"");
    static final Pattern PARENT = Pattern.compile("\"parent\"\\s*:\\s*\"([a-z0-9_:/.-]+)\"");
    static final Pattern TEXTURES = Pattern.compile("\"textures\"\\s*:\\s*\\{([^}]*)}");
    static final Pattern PAIR = Pattern.compile("\"([a-z0-9_]+)\"\\s*:\\s*\"([^\"]+)\"");
    /** Which texture variable represents the item best, in order. */
    static final List<String> PRIORITY = List.of("layer0", "all", "side", "front", "texture", "cross", "plant", "top", "end", "particle");

    public static void main(String[] args) throws Exception {
        int ok = 0, skipped = 0;
        StringBuilder out = new StringBuilder("# Generated by tools/VanillaItemIcons.java from the 26.3 client: one icon per vanilla item.\n"
                + "# Draw these only where y % 9 == 2 (single font provider, see the tool's javadoc).\nvanilla:\n");
        try (ZipFile client = new ZipFile(args[0])) {
            List<String> items = new ArrayList<>();
            client.stream().map(e -> e.getName()).filter(n -> n.startsWith("assets/minecraft/items/") && n.endsWith(".json")).forEach(items::add);
            Collections.sort(items);
            for (String entry : items) {
                String id = entry.substring("assets/minecraft/items/".length(), entry.length() - 5);
                String texture = texture(client, read(client, entry));
                if (texture == null) { skipped++; continue; }
                String[] k = texture.contains(":") ? texture.split(":", 2) : new String[]{"minecraft", texture};
                String path = "assets/" + k[0] + "/textures/" + k[1] + ".png";
                var file = client.getEntry(path);
                if (file == null || client.getEntry(path + ".mcmeta") != null) { skipped++; continue; }
                var image = ImageIO.read(client.getInputStream(file));
                if (image == null || image.getWidth() != image.getHeight()) { skipped++; continue; }
                int right = 0;
                for (int x = image.getWidth() - 1; x >= 0 && right == 0; x--)
                    for (int y = 0; y < image.getHeight(); y++)
                        if ((image.getRGB(x, y) >>> 24) != 0) { right = x + 1; break; }
                if (right == 0) { skipped++; continue; }
                float scale = 16f / image.getHeight();
                out.append("  item/").append(id).append(":\n")
                        .append("    texture: ").append(k[0]).append(':').append(k[1]).append(".png\n")
                        .append("    width: 16\n    height: 16\n    ascent: 8\n")
                        .append("    advance: ").append((int) (right * scale + 0.5F) + 1).append('\n')
                        .append("    offsets: [2]\n");
                ok++;
            }
        }
        Files.writeString(Path.of(args[1]), out);
        System.out.println("icons=" + ok + " skipped=" + skipped);
    }

    static String read(ZipFile zip, String name) throws Exception {
        var entry = zip.getEntry(name);
        return entry == null ? null : new String(zip.getInputStream(entry).readAllBytes());
    }

    /** items/<id>.json -> first referenced model -> textures along the parent chain -> best variable. */
    static String texture(ZipFile client, String itemJson) throws Exception {
        if (itemJson == null) return null;
        Matcher m = MODEL.matcher(itemJson);
        if (!m.find()) return null;
        String model = m.group(1);
        Map<String, String> textures = new HashMap<>();
        for (int depth = 0; model != null && depth < 8; depth++) {
            String key = model.contains(":") ? model.substring(model.indexOf(':') + 1) : model;
            String json = read(client, "assets/minecraft/models/" + key + ".json");
            if (json == null) break;
            Matcher t = TEXTURES.matcher(json);
            if (t.find()) {
                Matcher p = PAIR.matcher(t.group(1));
                while (p.find()) textures.putIfAbsent(p.group(1), p.group(2));  // child definitions win
            }
            Matcher parent = PARENT.matcher(json);
            model = parent.find() ? parent.group(1) : null;
        }
        for (String name : PRIORITY) {
            String value = textures.get(name);
            for (int hops = 0; value != null && value.startsWith("#") && hops < 8; hops++) value = textures.get(value.substring(1));
            if (value != null && !value.startsWith("#")) return value;
        }
        return null;
    }
}
